//! `INDEX.md` (M20.1 step 1, generated here in M20.2): one line per memory file, grouped by scope,
//! made from the files themselves with no model. Each write updates the lines of the files it
//! changed. The brief carries a project's lines, in the data block: they are made from text agents
//! wrote (file names, headings), so they are never instructions (mem-m1).
//!
//! ```text
//! # Index
//!
//! ## projects/app-3f9a1c
//!
//! - projects/app-3f9a1c/knowhow/deploy.md: deploy (Rollback, Staging), 4 entries
//! ```

use std::collections::BTreeMap;

use super::entry::{Doc, Line, Status};
use super::layout::MemFile;

/// The line of a file: its path, its title (or a know-how file's description), its sections and
/// how many entries it has that are not let go. None for files that have no line (the index, the
/// inbox).
pub fn line_of(file: &MemFile, doc: &Doc) -> Option<String> {
    if matches!(file, MemFile::Index | MemFile::Rejected | MemFile::Proposals) {
        return None;
    }
    let mut title = None;
    let mut description = None;
    let mut sections = Vec::new();
    for line in &doc.lines {
        let Line::Text(text) = line else { continue };
        if let Some(heading) = text.strip_prefix("## ") {
            sections.push(clip(heading.trim(), 40));
        } else if let Some(heading) = text.strip_prefix("# ").filter(|_| title.is_none()) {
            title = Some(clip(heading.trim(), 60));
        } else if let Some(said) = text.strip_prefix("description:").filter(|_| description.is_none()) {
            description = Some(clip(said.trim(), 100));
        }
    }
    let entries = doc.entries().filter(|e| e.header.status != Status::LetGo).count();
    let mut out = format!("- {}", file.rel());
    if let Some(name) = description.or(title) {
        out.push_str(&format!(": {name}"));
    }
    if !sections.is_empty() {
        sections.truncate(8);
        out.push_str(&format!(" ({})", sections.join(", ")));
    }
    out.push_str(&format!(", {entries} {}", if entries == 1 { "entry" } else { "entries" }));
    Some(super::entry::clean_text(&out))
}

fn clip(text: &str, max: usize) -> String {
    let mut out: String = text.chars().take(max).collect();
    if text.chars().count() > max {
        out.push('…');
    }
    out
}

/// The lines of an index, by the file each names.
pub fn parse(text: &str) -> BTreeMap<String, String> {
    text.lines()
        .filter_map(|line| {
            let rest = line.strip_prefix("- ")?;
            let end = rest.find([':', ' ', ',']).unwrap_or(rest.len());
            let rel = &rest[..end];
            MemFile::parse(rel).map(|_| (rel.to_string(), line.to_string()))
        })
        .collect()
}

/// The index of `lines`: a section per scope, the lines in path order.
pub fn render(lines: &BTreeMap<String, String>) -> String {
    let mut out = String::from("# Index\n\nGenerated by Glasscode from the memory files; it changes with them.\n");
    let mut scope = None;
    for (rel, line) in lines {
        let Some(file) = MemFile::parse(rel) else { continue };
        let key = file.scope().key();
        if scope.as_ref() != Some(&key) {
            out.push_str(&format!("\n## {key}\n\n"));
            scope = Some(key);
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// The index after files changed: `changed` holds each file's new text (None: removed).
pub fn update(index: Option<&str>, changed: &[(MemFile, Option<&str>)]) -> String {
    let mut lines = index.map(parse).unwrap_or_default();
    for (file, text) in changed {
        let rel = file.rel();
        match text.map(Doc::parse).and_then(|doc| line_of(file, &doc)) {
            Some(line) => {
                lines.insert(rel, line);
            }
            None => {
                lines.remove(&rel);
            }
        }
    }
    render(&lines)
}

/// The lines of one scope (`projects/app-3f9a1c`, [`super::Scope::key`]).
pub fn lines_of(index: &str, scope: &str) -> Vec<String> {
    parse(index).into_iter().filter(|(rel, _)| MemFile::parse(rel).is_some_and(|file| file.scope().key() == scope)).map(|(_, line)| line).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths::ProjectKey;

    #[test]
    fn the_index_follows_the_files() {
        let key = ProjectKey::parse("app-3f9a1c").unwrap();
        let deploy = MemFile::Knowhow(key.clone(), "deploy".into());
        let text = "---\nname: deploy\ndescription: How app deploys\n---\n# deploy\n\n## Rollback\n\n- Roll back with make. <!-- id=a1 status=learned kind=knowhow source=session:s -->\n\n## Staging\n";
        let index = update(None, &[(deploy.clone(), Some(text)), (MemFile::Profile, Some("# profile\n"))]);
        assert!(index.contains("## projects/app-3f9a1c\n\n- projects/app-3f9a1c/knowhow/deploy.md: How app deploys (Rollback, Staging), 1 entry\n"), "{index}");
        assert!(index.contains("## you\n\n- you/profile.md: profile, 0 entries\n"), "{index}");
        assert_eq!(lines_of(&index, "projects/app-3f9a1c").len(), 1);
        // Again from its own text, and with the file gone.
        assert_eq!(update(Some(&index), &[]), index);
        let gone = update(Some(&index), &[(deploy, None)]);
        assert!(!gone.contains("deploy") && gone.contains("you/profile.md"), "{gone}");
        assert_eq!(line_of(&MemFile::Proposals, &Doc::default()), None);
    }
}
